//! Markdown rendering for the repository and project reports selected by the documentation owner.
use super::{Confidence, ProjectResult, SynthesisResult};
use crate::protocol::Id;
use std::fmt::Write;

pub(in crate::services::graph::repository_analysis) struct DocumentationSource<'a> {
    pub run: &'a Id,
    pub revision: &'a str,
    pub view: &'a Id,
    pub view_digest: &'a str,
    pub commit: &'a str,
    pub computed_at_ms: i64,
    pub partial: bool,
}

fn text(value: &str) -> String {
    let mut escaped = String::with_capacity(value.len());
    for character in value.trim().chars() {
        match character {
            '&' => escaped.push_str("&amp;"),
            '<' => escaped.push_str("&lt;"),
            '>' => escaped.push_str("&gt;"),
            '\n' | '\r' | '\t' => escaped.push(' '),
            '\\' | '|' | '`' | '*' | '_' | '[' | ']' | '#' => {
                escaped.push('\\');
                escaped.push(character);
            }
            character if !character.is_control() => escaped.push(character),
            _ => {}
        }
    }
    escaped
}

fn provenance(
    name: &str,
    source: &DocumentationSource<'_>,
    confidence: Confidence,
    model: &str,
) -> String {
    let confidence = match confidence {
        Confidence::High => "High",
        Confidence::Medium => "Medium",
        Confidence::Low => "Low",
    };
    let coverage = if source.partial {
        "Partial"
    } else {
        "Complete"
    };
    format!(
        "# {}\n\nGenerated by DevWorks from repository analysis.\n\n\
         - Confidence: {confidence}\n- Model: {}\n- Analysis run: {}\n- Analysis revision: {}\n\
         - Graph view: {}\n- View digest: {}\n- Source commit: {}\n- Analysis time: {}\n\
         - Coverage: {coverage}\n\n",
        text(name),
        text(model),
        source.run.as_str(),
        text(source.revision),
        source.view.as_str(),
        text(source.view_digest),
        text(source.commit),
        jiff::Timestamp::from_millisecond(source.computed_at_ms).map_or_else(
            |_| source.computed_at_ms.to_string(),
            |time| time.to_string()
        ),
    )
}

pub(in crate::services::graph::repository_analysis) fn repository(
    name: &str,
    source: &DocumentationSource<'_>,
    synthesis: &SynthesisResult,
    projects: &[&ProjectResult],
    languages: &[(String, String)],
    dependencies: &[(String, String)],
    dependents: &[(String, String)],
) -> String {
    let mut document = provenance(name, source, synthesis.result.confidence, &synthesis.model);
    let _ = writeln!(
        document,
        "## Summary\n\n{}\n",
        text(&synthesis.result.summary)
    );
    for (heading, entries) in [
        ("Languages", languages),
        ("Dependencies", dependencies),
        ("Dependents", dependents),
    ] {
        if !entries.is_empty() {
            let _ = writeln!(document, "## {heading}\n");
            for (name, description) in entries {
                let _ = writeln!(document, "- **{}**: {}", text(name), text(description));
            }
            document.push('\n');
        }
    }
    if !projects.is_empty() {
        document.push_str("## Projects\n\n");
        for report in projects {
            let _ = writeln!(
                document,
                "### {}\n\n{}\n",
                text(&report.subject.name),
                text(&report.result.summary),
            );
        }
    }
    document
}

pub(in crate::services::graph::repository_analysis) fn project(
    source: &DocumentationSource<'_>,
    report: &ProjectResult,
) -> String {
    let project = &report.result;
    let mut document = provenance(
        &report.subject.name,
        source,
        project.confidence,
        &report.model,
    );
    let _ = writeln!(document, "## Summary\n\n{}\n", text(&project.summary));
    if !project.endpoints.is_empty() {
        document.push_str(
            "## Endpoints\n\n| Method | Route | Description | Request | Response |\n\
             | --- | --- | --- | --- | --- |\n",
        );
        for endpoint in &project.endpoints {
            let _ = writeln!(
                document,
                "| {} | {} | {} | {} | {} |",
                text(&endpoint.http_method),
                text(&endpoint.route),
                text(&endpoint.description),
                text(endpoint.request_model.as_deref().unwrap_or("")),
                text(endpoint.response_model.as_deref().unwrap_or("")),
            );
        }
        document.push('\n');
    }
    if !project.services.is_empty() {
        document.push_str("## Services\n\n");
        for service in &project.services {
            let _ = writeln!(document, "### {}\n", text(&service.name));
            if let Some(interface) = &service.interface_name {
                let _ = writeln!(document, "Implements {}.\n", text(interface));
            }
            if !service.lifetime.is_empty() {
                let _ = writeln!(document, "Lifetime: {}.\n", text(&service.lifetime));
            }
            let _ = writeln!(document, "{}\n", text(&service.description));
        }
    }
    for (heading, entries) in [
        ("External Dependencies", &project.external_dependencies),
        ("Database Tables", &project.database_tables),
    ] {
        if !entries.is_empty() {
            let _ = writeln!(document, "## {heading}\n");
            for entry in entries {
                let _ = writeln!(document, "- {}", text(entry));
            }
            document.push('\n');
        }
    }
    document
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn repository_document_labels_partial_source_and_preserves_the_selected_projects() {
        let run = Id::new("analysis-1").unwrap();
        let view = Id::new("view-1").unwrap();
        let source = DocumentationSource {
            run: &run,
            revision: "7",
            view: &view,
            view_digest: "exact-digest",
            commit: "exact-sha",
            computed_at_ms: 0,
            partial: true,
        };
        let synthesis: SynthesisResult = serde_json::from_value(serde_json::json!({
            "repository":"repo", "view":"view-1", "projectCheckpoints":["project-checkpoint"],
            "result":{"repoSummary":"Repository overview","confidence":"medium"},
            "request":"request-1", "attempt":"attempt-1", "model":"reviewed-model"
        }))
        .unwrap();
        let report: ProjectResult = serde_json::from_value(serde_json::json!({
            "checkpoint":"project-checkpoint",
            "subject":{"id":"project", "repository":"repo", "view":"view-1",
            "name":"App", "repositoryName":"Repo", "evidence":[]},
            "result":{"summary":"Native service","confidence":"high",
                "endpoints":[{"route":"/x|y", "httpMethod":"GET", "description":"Returns <records>",
                    "requestModel":null, "responseModel":"Record"}],
                "services":[{"name":"ReportService", "description":"Reads reports",
                    "interfaceName":"IReportService", "lifetime":"Singleton"}],
                "externalDependencies":["socket"], "databaseTables":["reports"]},
            "request":"request-2", "attempt":"attempt-2", "model":"reviewed-model"
        }))
        .unwrap();
        let repo = repository(
            "Repo",
            &source,
            &synthesis,
            &[&report],
            &[("Rust".into(), "10 files".into())],
            &[("requests".into(), "CALLS".into())],
            &[("desktop".into(), "REFERENCES_PACKAGE".into())],
        );
        for evidence in [
            "Coverage: Partial",
            "Analysis run: analysis-1",
            "View digest: exact-digest",
            "Source commit: exact-sha",
            "## Languages",
            "## Dependencies",
            "## Dependents",
            "### App\n\nNative service",
        ] {
            assert!(repo.contains(evidence), "{evidence}");
        }
        let doc = project(&source, &report);
        assert!(doc.contains("GET | /x\\|y | Returns &lt;records&gt; |  | Record"));
        assert!(doc.contains("Implements IReportService"));
        assert!(doc.contains("## External Dependencies\n\n- socket"));
        assert!(doc.contains("## Database Tables\n\n- reports"));
    }
}
