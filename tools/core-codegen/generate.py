#!/usr/bin/env python3
"""Generate devworks-core domain records, per-family operation inputs and the operation registry.

Sources (edit these, never the generated Rust):
  tools/contracts-eval/domain-spec.json             domain records, operation fields, result types, schema revisions
  docs/architecture/contracts/family-coverage.json  family, owner, modes, envelopes, selectors, policies

Outputs (deterministic, rustfmt-formatted, checked for drift in CI):
  crates/devworks-core/src/protocol/records.rs
  crates/devworks-core/src/protocol/results.rs
  crates/devworks-core/src/operations/mod.rs and one module per family
  crates/devworks-core/src/registry/catalog.rs

Uses only the Python standard library plus `rustfmt` from the pinned Rust toolchain.
"""
from pathlib import Path
import json
import re
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[2]
SPEC = json.loads((ROOT / 'tools/contracts-eval/domain-spec.json').read_text(encoding='utf-8'))
REGISTER = json.loads((ROOT / 'docs/architecture/contracts/family-coverage.json').read_text(encoding='utf-8'))
CORE = ROOT / 'crates/devworks-core/src'
CONTRACTS = ROOT / 'docs/architecture/contracts'
HEADER = '// @generated by tools/core-codegen/generate.py from domain-spec.json and family-coverage.json.\n// Do not edit by hand; regenerate and commit the result.\n'

TYPES = SPEC['types']
DOMAIN_OPS = SPEC['operations']
LEGACY_RESULTS = SPEC['earlierInputResults']
# Operations that negotiate more than the initial schema revision, with every revision they accept.
REVISIONS = SPEC.get('schemaRevisions', {})

# Hand-maintained protocol modules and the names generated code may reference from them.
