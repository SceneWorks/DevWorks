def write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open('w', encoding='utf-8', newline='\n') as f:
        f.write(text)
    return path


def main():
    ops = operations()
    by_family = {}
    for fam, o in ops:
        by_family.setdefault(fam['family'], (fam, []))[1].append(o)
    written = [
        write(CORE / 'protocol/records.rs', gen_records()),
        write(CORE / 'protocol/results.rs', gen_results(ops)),
        write(CORE / 'operations/mod.rs', gen_operations_mod(REGISTER['families'])),
        write(CORE / 'registry/catalog.rs', gen_catalog(ops)),
    ]
    family_dir = CORE / 'operations'
    expected = {'mod.rs'} | {f'{f}.rs' for f in by_family}
    for stale in family_dir.glob('*.rs'):
        if stale.name not in expected:
            stale.unlink()
    for name, (fam, fops) in by_family.items():
        written.append(write(family_dir / f'{name}.rs', gen_family(fam, fops)))
    subprocess.run(['rustfmt', '--edition', '2024', *map(str, written)], check=True)
    print(json.dumps({'families': len(by_family), 'operations': len(ops),
                      'inputBindings': sum(len(bindings(o)) for _, o in ops), 'domainTypes': len(TYPES)}))


if __name__ == '__main__':
    main()
