DATA = set('DataScope ViewSelection Coverage GitOid GraphPage RetrievalPage DeliveryBarrier DeliverySnapshot '
           'ArtifactTags'.split())
SUPPORT = set('Check Label Text Content Cursor PlanItems PlanFeatures Items NonEmpty Rows Page HistoryPage Limit '
              'Depth Port ByteLimit TokenBudget PathSet Url RelativePath Money SignedCounter PositiveCounter Finite Probability '
              'DynamicJson DomainErrorCode DomainFault'.split())
# Hand-written support types that gate a member by schema revision themselves.
GATED_SUPPORT = {'HistoryPage'}
PRIMITIVE = {'bool', 'i32', 'Option'}

SPECIALIZED = {
    'command-request.schema.json': 'crate::protocol::CommandRequest',
    'query-request.schema.json': 'crate::protocol::QueryRequest',
    'graph-read-request.schema.json': 'crate::protocol::data::GraphReadRequest',
    'artifact-command-request.schema.json': 'crate::protocol::data::ArtifactCommandRequest',
    'artifact-query-request.schema.json': 'crate::protocol::data::ArtifactQueryRequest',
    'artifact-deletion-request.schema.json': 'crate::protocol::data::ArtifactDeletionRequest',
    'git-command-request.schema.json': 'crate::protocol::data::GitCommandRequest',
    'index-command-request.schema.json': 'crate::protocol::data::IndexCommandRequest',
    'release-command-request.schema.json': 'crate::protocol::data::ReleaseCommandRequest',
    'retrieval-request.schema.json': 'crate::protocol::data::RetrievalRequest',
    'session-command-request.schema.json': 'crate::protocol::provider::SessionCommandRequest',
    'session-query-request.schema.json': 'crate::protocol::provider::SessionQueryRequest',
    'addon-command-request.schema.json': 'crate::protocol::addons::AddonCommandRequest',
}
AUTHORITY = {
    'ScopedRead': 'ScopedRead', 'Scoped': 'Scoped', 'Existing host command authority': 'ExistingHostCommand',
    'HostMaintenance': 'HostMaintenance', 'Configuration': 'Configuration',
    'HumanConfiguration': 'HumanConfiguration', 'HumanDecision': 'HumanDecision',
    'HumanMaintenance': 'HumanMaintenance',
}
EFFECT = {
    'ReadOnly or declared external read': 'ReadOnly', 'Local': 'Local',
    'Existing journaled command contract': 'ExistingJournaled', 'Journaled': 'Journaled',
    'External': 'External', 'Inference': 'Inference', 'ActionDependent': 'ActionDependent',
}


def fail(msg):
    sys.exit('generate.py: ' + msg)


def pascal(s):
    return ''.join(p[:1].upper() + p[1:] for p in re.split('[._-]', s))


def snake(s):
    return re.sub('[^a-z0-9]+', '_', s.lower())


def rust(t):
    return 'Option<' + rust(t[1:]) + '>' if t.startswith('?') else t


def tokens(t):
    return set(re.findall(r'[A-Za-z_][A-Za-z0-9_]*', t))


def imports(used, records_glob=True):
    used = set(used) - PRIMITIVE
    unknown = used - SHARED - PROVIDER - DATA - SUPPORT - set(TYPES)
    if unknown:
        fail('unresolved type names ' + ', '.join(sorted(unknown)))
    out = []
    if records_glob:
        out.append('#[allow(unused_imports)]\nuse crate::protocol::records::*;')
    out.append('#[allow(unused_imports)]\nuse crate::protocol::support::*;')
    for mod, names in (('crate::protocol', SHARED), ('crate::protocol::provider', PROVIDER),
                       ('crate::protocol::data', DATA)):
        hit = sorted(used & names)
        if hit:
            out.append(f'use {mod}::{{{", ".join(hit)}}};')
    return out


def camel(s):
    return re.sub(r'_([a-z])', lambda m: m[1].upper(), s)


def fields(fs, indent='    ', pub=True, since=None, one=(), schema=None):
    """`one`: members of an exactly-one choice (rendered without null); `schema`: extra keywords."""
    since = since or {}
    schema = schema or {}
    lines = []
    for n, t in fs.items():
        extra = ''.join(f', {json.dumps(k)} = {json.dumps(v)}' for k, v in schema.get(n, {}).items())
        if n in since:
            # A later-revision member is omitted or present, never null (see `gated_member`).
            lines.append(indent + '#[serde(default, skip_serializing_if = "Option::is_none", '
                         'deserialize_with = "gated_member")]')
            lines.append(indent + f'#[schemars(with = "{rust(t[1:])}", extend("x-since" = {since[n]}{extra}))]')
        elif t.startswith('?'):
            lines.append(indent + '#[serde(default, skip_serializing_if = "Option::is_none")]')
            if n in one:
                lines.append(indent + f'#[schemars(with = "{rust(t[1:])}")]')
        lines.append(indent + ('pub ' if pub else '') + f'{n}: {rust(t)},')
    return '\n'.join(lines)


def choice(fs, one, since):
    """`oneOf` of an exactly-one member choice: each alternative lists the full required set (in
    field order) with that member; one introduced later carries its `x-since`, so an earlier
    revision's document folds back to the plain required list."""
    alts = []
    for m in one:
        req = [camel(n) for n, t in fs.items() if not t.startswith('?') or n == m]
        alts.append({'required': req, **({'x-since': since[m]} if m in since else {})})
    return f'#[schemars(extend("oneOf" = {json.dumps(alts)}))]\n'


def record_attrs(d):
    out = ''
    if d.get('schemaName'):
        out += f'#[schemars(rename = "{d["schemaName"]}")]\n'
    if d.get('earlierName'):
        earlier = {'name': d['earlierName'], 'before': min(d['since'].values())}
        out += f'#[schemars(extend("x-earlier" = {json.dumps(earlier)}))]\n'
    return out


def check_since(owner, fs, since):
    """A member added in a later schema revision is optional, so earlier revisions omit it."""
    for n, r in since.items():
        if n not in fs or not fs[n].startswith('?') or not isinstance(r, int) or r < 2:
            fail(f'{owner}.{n}: a revision-gated member must be an optional field with revision >= 2')


def revisioned_types():
    """Domain types whose wire shape depends on the schema revision: records with gated members,
    and records/unions that (transitively) contain one."""
    for name, d in TYPES.items():
        if 'since' in d:
            if d['kind'] != 'record':
                fail(f'{name}: only records may gate members by schema revision')
            check_since(name, d['fields'], d['since'])
    out = {n for n, d in TYPES.items() if d.get('since')}
    while True:
        grown = set(out)
        for name, d in TYPES.items():
            members = (d['fields'].values() if d['kind'] == 'record'
                       else [t for fs in d['variants'].values() for t in fs.values()] if d['kind'] == 'union' else [])
            if any(tokens(t) & out for t in members):
                grown.add(name)
        if grown == out:
            return out
        out = grown


def revisioned(name, fs, since, rc, union_variants=None):
    """`Revisioned` impl: clear members introduced after the revision, recurse into others."""
    head = f'impl Revisioned for {name} {{\n    fn retain_revision(&mut self, revision: u32) {{'
    if union_variants is not None:
        arms = []
        for v, vfs in union_variants.items():
            inner = [n for n, t in vfs.items() if tokens(t) & rc]
            if inner:
                calls = ' '.join(f'{n}.retain_revision(revision);' for n in inner)
                arms.append(f'            Self::{v} {{ {", ".join(inner)}, .. }} => {{ {calls} }}')
        if not arms:
            return f'impl Revisioned for {name} {{\n    fn retain_revision(&mut self, _: u32) {{}}\n}}'
        if len(arms) == 1 and len(union_variants) > 1:
            # One revisioned alternative among several: an `if let`, not a single-arm match.
            pattern, calls = arms[0].strip().split(' => ', 1)
            return '\n'.join([head, f'        if let {pattern} = self {calls}', '    }', '}'])
        if len(arms) < len(union_variants):
            arms.append('            _ => {}')
        return '\n'.join([head, '        match self {', *arms, '        }', '    }', '}'])
    body = [f'        if revision < {since[n]} {{\n            self.{n} = None;\n        }}'
            + (f' else {{\n            self.{n}.retain_revision(revision);\n        }}' if tokens(fs[n]) & rc else '')
            for n in fs if n in since]
    body += [f'        self.{n}.retain_revision(revision);' for n, t in fs.items() if n not in since and tokens(t) & rc]
    if not body:
        return f'impl Revisioned for {name} {{\n    fn retain_revision(&mut self, _: u32) {{}}\n}}'
    return '\n'.join([head, *body, '    }', '}'])


def checks(fs, base='self.', indent='        '):
    return '\n'.join(indent + f'{base}{n}.check()?;' for n in fs)


DERIVE = '#[derive(Clone, Debug, Serialize, Deserialize, JsonSchema)]\n'
RECORD = DERIVE + '#[serde(rename_all = "camelCase", deny_unknown_fields)]\n'
TAGGED = DERIVE + '#[serde(tag = "kind", rename_all_fields = "camelCase", deny_unknown_fields)]\n'


def type_tokens():
    used = set()
    for d in TYPES.values():
        if d['kind'] == 'record':
            for t in d['fields'].values():
                used |= tokens(t)
        elif d['kind'] == 'union':
            for fs in d['variants'].values():
                for t in fs.values():
                    used |= tokens(t)
    return used


def gen_records():
    clash = (SUPPORT | SHARED | PROVIDER | DATA) & set(TYPES)
    if clash:
        fail('domain type names clash with hand-written protocol names: ' + ', '.join(sorted(clash)))
    out = [HEADER, '//! Domain records, enums and tagged unions shared by catalog operations (AD69-AD71).',
           '//! `Check` applies nested bounds and the recorded pure cross-field rules in `protocol::rules`.',
           *imports(type_tokens(), records_glob=False),
           'use schemars::JsonSchema;', 'use serde::{Deserialize, Serialize};', '']
    for name, d in TYPES.items():
        if d['kind'] == 'record':
            since = d.get('since', {})
            out += [RECORD + record_attrs(d) + f'pub struct {name} {{', fields(d['fields'], since=since), '}',
                    f'impl Check for {name} {{', '    fn check(&self) -> Result<(), String> {',
                    checks(d['fields']),
                    f'        crate::protocol::rules::record("{name}", &serde_json::to_value(self).map_err(|e| e.to_string())?)?;',
                    '        Ok(())', '    }', '}', '']
            if name in RC:
                out += [revisioned(name, d['fields'], since, RC), '']
        elif d['kind'] == 'enum':
            variants = ['    ' + pascal(v) + ',' if v[0].isupper() else f'    #[serde(rename = "{v}")]\n    {pascal(v)},'
                        for v in d['values']]
            out += [DERIVE + f'pub enum {name} {{', *variants, '}',
                    f'impl Check for {name} {{', '    fn check(&self) -> Result<(), String> {', '        Ok(())', '    }', '}', '']
        else:
            out += [TAGGED + f'pub enum {name} {{']
            for v, fs in d['variants'].items():
                out += [f'    {v} {{', fields(fs, '        ', pub=False), '    },']
            out += ['}', f'impl Check for {name} {{', '    fn check(&self) -> Result<(), String> {', '        match self {']
            for v, fs in d['variants'].items():
                out += [f'            Self::{v} {{ {", ".join(fs)} }} => {{', checks(fs, '', '                '), '            }']
            out += ['        }', '        Ok(())', '    }', '}', '']
            if name in RC:
                out += [revisioned(name, {}, {}, RC, d['variants']), '']
    return '\n'.join(out) + '\n'


def operations():
    """Flatten the register into (family, op-record, [(mode, policy)]) in register order."""
    out = []
    names = set()
    for fam in REGISTER['families']:
        if not re.fullmatch('[a-z][a-z_]*', fam['family']):
            fail('family name is not a Rust module name: ' + fam['family'])
        for o in fam['operations']:
            n = o['operation']
            if n in names or n.split('.')[0] != fam['family']:
                fail('duplicate or misplaced operation ' + n)
            names.add(n)
            if [m['mode'] for m in o['modePolicies']] != o['requestModes'] or not o['requestModes']:
                fail('mode policies disagree with request modes for ' + n)
            if o['inputSchema'] == 'domain-request.schema.json':
                d = DOMAIN_OPS.get(n) or fail('domain operation missing from domain-spec: ' + n)
                spec_modes = ['Query', 'Command'] if d['mode'] == 'Hybrid' else [d['mode']]
                if spec_modes != o['requestModes'] or d['result'] != o['resultValueType']:
                    fail('domain-spec and register disagree for ' + n)
                if o['selectionConstraint'] != {'pointer': '/body/kind', 'equals': n}:
                    fail('domain envelope selector must be /body/kind for ' + n)
                every = {**d.get('fields', {}), **d.get('queryFields', {}), **d.get('commandFields', {})}
                check_since(n, every, d.get('since', {}))
            else:
                if o['inputSchema'] not in SPECIALIZED:
                    fail('unknown specialized envelope ' + o['inputSchema'])
                if LEGACY_RESULTS.get(n) != o['resultValueType'] or len(o['requestModes']) != 1:
                    fail('specialized binding mismatch for ' + n)
            if o['resultSelectionConstraint'] != {'pointer': '/kind', 'equals': n}:
                fail('result selector must name the originating operation for ' + n)
            check_revisions(o)
            out.append((fam, o))
    if names != set(DOMAIN_OPS) | set(LEGACY_RESULTS):
        fail('register and domain-spec operation sets differ')
    if set(REVISIONS) - names:
        fail('schema revisions declared for unknown operations: ' + ', '.join(sorted(set(REVISIONS) - names)))
    if len(out) != REGISTER['operationCount'] or len(REGISTER['families']) != REGISTER['familyCount']:
        fail('register counts disagree with its families')
    return out


def revision_doc(base, name, revision):
    """`<base>.schema.json` or the `<base>.rK.schema.json` revision document with K <= revision."""
    m = re.fullmatch(re.escape(base) + r'(?:\.r([0-9]+))?\.schema\.json', name or '')
    return m is not None and (m[1] is None or 2 <= int(m[1]) <= revision)


def check_revisions(o):
    """The register's per-revision bindings must list exactly the spec's supported revisions."""
    n = o['operation']
    revs = o.get('schemaRevisions') or fail('register lists no schema revisions for ' + n)
    numbers = [r['revision'] for r in revs]
    if numbers != REVISIONS.get(n, [1]):
        fail(f'register revisions {numbers} differ from domain-spec for {n}')
    if numbers[0] != 1 or numbers != sorted(set(numbers)):
        fail('schema revisions must start at 1 and increase for ' + n)
    if revs[0]['inputSchema'] != o['inputSchema'] or revs[0]['resultSchema'] != o['resultSchema']:
        fail('revision 1 must bind the operation\'s base schemas for ' + n)
    base = o['inputSchema'].removesuffix('.schema.json')
    for r in revs:
        if not (revision_doc(base, r['inputSchema'], r['revision'])
                and revision_doc('operation-result', r['resultSchema'], r['revision'])):
            fail(f'revision {r["revision"]} of {n} binds foreign schema documents')
    # A member introduced at N in this operation's input or result is reachable only when the
    # operation registers N or later; otherwise it would always be refused or projected away.
    carried = introduced_in(o)
    if carried and max(carried) > numbers[-1]:
        fail(f'{n} carries a member introduced at schema revision {max(carried)} '
             f'but registers only revisions {numbers}')


def type_since(name, seen=None):
    """Revisions at which members of domain type `name` (transitively) were introduced."""
    seen = set() if seen is None else seen
    d = TYPES.get(name)
    if d is None or name in seen:
        return set()
    seen.add(name)
    out = set(d.get('since', {}).values())
    members = (d['fields'].values() if d['kind'] == 'record'
               else [t for fs in d['variants'].values() for t in fs.values()] if d['kind'] == 'union' else [])
    for t in members:
        for tok in tokens(t):
            out |= type_since(tok, seen)
    return out


def doc_since(doc, pointer=None, equals=None):
    """`x-since` revisions in a schema document, restricted to the branch a selector picks."""
    def resolve(node):
        while isinstance(node, dict) and str(node.get('$ref', '')).startswith('#/$defs/'):
            node = doc['$defs'][node['$ref'][len('#/$defs/'):]]
        return node

    def collect(node, seen):
        out = set()
        if isinstance(node, dict):
            if isinstance(node.get('x-since'), int):
                out.add(node['x-since'])
            ref = str(node.get('$ref', ''))
            if ref.startswith('#/$defs/') and ref not in seen:
                seen.add(ref)
                out |= collect(doc['$defs'][ref[len('#/$defs/'):]], seen)
            for k, v in node.items():
                if k != '$defs':
                    out |= collect(v, seen)
        elif isinstance(node, list):
            for v in node:
                out |= collect(v, seen)
        return out

    def alternatives(node):
        # A union is a node without its own properties; an object's own `oneOf` (a choice of
        # required members, such as exactly one scope) belongs to that object's branch.
        node = resolve(node)
        alts = node.get('oneOf') or node.get('anyOf')
        if alts and 'properties' not in node:
            return [b for a in alts for b in alternatives(a)]
        return [node]

    if pointer is None:
        return collect(doc, set())
    segments = pointer.strip('/').split('/')

    def walk(node, i):
        out = set()
        for branch in alternatives(node):
            props = branch.get('properties', {})
            if i == len(segments) - 1:
                tag = resolve(props.get(segments[i], {}))
                if tag.get('const') == equals or equals in tag.get('enum', []):
                    out |= collect(branch, set())
            elif segments[i] in props:
                out |= walk(props[segments[i]], i + 1)
                out |= {props[segments[i]]['x-since']} if isinstance(props[segments[i]].get('x-since'), int) else set()
                for name, p in props.items():
                    if name != segments[i]:
                        out |= collect(p, set())
        return out
    return walk(doc, 0)


def latest_doc(base):
    """The newest recorded revision document of `base` (only those carry `x-since`)."""
    found = sorted(CONTRACTS.glob(base + '.r*.schema.json'),
                   key=lambda p: int(re.search(r'\.r([0-9]+)\.schema\.json$', p.name)[1]))
    return json.loads(found[-1].read_text(encoding='utf-8')) if found else None


def introduced_in(o):
    """Every revision at which a member of this operation's selected input or result appeared:
    domain types and domain inputs from domain-spec, specialized envelopes and results from the
    recorded revision documents (selected branch only)."""
    n = o['operation']
    d = DOMAIN_OPS.get(n)
    out = set()
    if d:
        out |= set(d.get('since', {}).values())
        for key in ('fields', 'queryFields', 'commandFields'):
            for t in d.get(key, {}).values():
                for tok in tokens(t):
                    out |= type_since(tok)
        result_type = d['result']
    else:
        result_type = LEGACY_RESULTS[n]
        doc = latest_doc(o['inputSchema'].removesuffix('.schema.json'))
        if doc is not None:
            sel = o['selectionConstraint']
            out |= doc_since(doc, sel['pointer'], sel['equals']) if sel else doc_since(doc)
    for tok in tokens(result_type):
        out |= type_since(tok)
    results = latest_doc('operation-result')
    if results is not None:
        out |= doc_since(results, '/kind', n)
    return out


def bindings(o):
    """Per-mode input bindings: (mode, struct or envelope path, variant name, fields-or-None)."""
    n = o['operation']
    action = pascal(n.split('.', 1)[1])
    if o['inputSchema'] != 'domain-request.schema.json':
        return [(o['requestModes'][0], SPECIALIZED[o['inputSchema']], action, None)]
    d = DOMAIN_OPS[n]
    if d['mode'] == 'Hybrid':
        return [(m, f'{action}{m}Input', f'{action}{m}', d[m.lower() + 'Fields']) for m in ('Query', 'Command')]
    return [(d['mode'], f'{action}Input', action, d['fields'])]


def gen_family(fam, ops):
    used = set()
    for o in ops:
        for _, _, _, fs in bindings(o):
            for t in (fs or {}).values():
                used |= tokens(t)
    out = [HEADER, f'//! Selected-operation inputs for the `{fam["family"]}` family (owner: {fam["owner"]}).',
           '//!', f'//! {fam["effectAndAuthority"]}', '//!',
           '//! Domain-envelope inputs are the `/body` members other than the `kind` discriminator; the',
           '//! registry decodes a body only into the input of the operation and mode the host selected.',
           '//! Specialized envelopes keep their recorded candidate shape and selector.',
           *imports(used), 'use crate::registry::Mode;']
    if any(fs is not None for o in ops for _, _, _, fs in bindings(o)):
        out += ['use schemars::JsonSchema;', 'use serde::{Deserialize, Serialize};']
    out.append('')
    local = set()
    for o in ops:
        for mode, ty, _, fs in bindings(o):
            if fs is None:
                continue
            if ty in TYPES or ty in local:
                fail('input type name clash ' + ty)
            local.add(ty)
            d = DOMAIN_OPS[o['operation']]
            since = {k: r for k, r in d.get('since', {}).items() if k in fs}
            one = d.get('exactlyOne', [])
            out += [f'/// `{o["operation"]}` {mode} input.',
                    RECORD + (choice(fs, one, since) if one else '') + f'pub struct {ty} {{',
                    fields(fs, since=since, one=one, schema=d.get('fieldSchema')), '}',
                    f'impl Check for {ty} {{', '    fn check(&self) -> Result<(), String> {', checks(fs),
                    '        Ok(())', '    }', '}', revisioned(ty, fs, since, RC), '']
    out += [f'/// An admitted input of the `{fam["family"]}` family, built only for the selected operation and mode.',
            '#[derive(Clone, Debug)]', 'pub enum Input {']
    for o in ops:
        for mode, ty, variant, _ in bindings(o):
            out.append(f'    /// `{o["operation"]}` ({mode}).\n    {variant}({ty}),')
    out += ['}', 'impl Input {', '    pub fn operation(&self) -> &\'static str {', '        match self {']
    for o in ops:
        for _, _, variant, _ in bindings(o):
            out.append(f'            Self::{variant}(_) => "{o["operation"]}",')
    out += ['        }', '    }', '    pub fn mode(&self) -> Mode {', '        match self {']
    for o in ops:
        for mode, _, variant, _ in bindings(o):
            out.append(f'            Self::{variant}(_) => Mode::{mode},')
    out += ['        }', '    }', '}']
    return '\n'.join(out) + '\n'


def gen_operations_mod(families):
    out = [HEADER, '//! Per-family operation modules. Each module owns the typed inputs of its catalog operations;',
           '//! [`OperationInput`] is the already-selected input handed from the gateway to a use case. It',
           '//! is never deserialized directly, so one operation\'s body cannot select another operation.',
           'use crate::registry::Mode;', '']
    out += [f'pub mod {f["family"]};' for f in families]
    out += ['', '/// The typed input of exactly one admitted operation and mode.', '#[derive(Clone, Debug)]',
            'pub enum OperationInput {']
    out += [f'    {pascal(f["family"])}({f["family"]}::Input),' for f in families]
    out += ['}', 'impl OperationInput {', '    pub fn operation(&self) -> &\'static str {', '        match self {']
    out += [f'            Self::{pascal(f["family"])}(i) => i.operation(),' for f in families]
    out += ['        }', '    }', '    pub fn mode(&self) -> Mode {', '        match self {']
    out += [f'            Self::{pascal(f["family"])}(i) => i.mode(),' for f in families]
    out += ['        }', '    }', '}']
    return '\n'.join(out) + '\n'


def gen_results(ops):
    results = [(o['operation'], o['resultValueType']) for _, o in ops]
    used = {'Protocol', 'QueryId', 'ReadStamp', 'OperationId', 'Revision', 'CorrelationId', 'CommandReply',
            'DomainFault', 'Check'}
    for _, t in results:
        used |= tokens(t)
    out = [HEADER, '//! Typed operation results, the generic domain decision and the query/command/completion replies.',
           '//! Each `OperationResult` variant carries the exact originating operation name; the gateway',
           '//! refuses to publish a result whose discriminator differs from the admitted operation.',
           *imports(used), 'use schemars::JsonSchema;', 'use serde::{Deserialize, Serialize};', '',
           TAGGED + 'pub enum OperationResult {']
    out += [f'    #[serde(rename = "{n}")]\n    {pascal(n)} {{ value: {rust(t)} }},' for n, t in results]
    out += ['}', 'impl OperationResult {', '    pub fn operation(&self) -> &\'static str {', '        match self {']
    out += [f'            Self::{pascal(n)} {{ .. }} => "{n}",' for n, _ in results]
    out += ['        }', '    }', '}', 'impl Check for OperationResult {', '    fn check(&self) -> Result<(), String> {',
            '        match self {']
    out += [f'            Self::{pascal(n)} {{ value }} => value.check()?,' for n, _ in results]
    # HistoryPage is a support type with its own revision-2 member (the tail checkpoint).
    projected = [n for n, t in results if tokens(t) & (RC | GATED_SUPPORT)]
    out += ['        }',
            '        crate::protocol::rules::result(self.operation(), &serde_json::to_value(self).map_err(|e| e.to_string())?)',
            '    }', '}',
            '/// Projects a result onto a negotiated schema revision: members introduced after it are removed.',
            'impl Revisioned for OperationResult {', '    fn retain_revision(&mut self, revision: u32) {',
            '        match self {',
            *[f'            Self::{pascal(n)} {{ value }} => value.retain_revision(revision),' for n in projected],
            *(['            _ => {}'] if len(projected) < len(results) else []),
            '        }', '    }', '}', '',
            '/// Generic recorded decision. Outcome variants cannot mint human authority or turn an external',
            '/// uncertainty into success.',
            TAGGED + '''pub enum DomainDecision {
    Applied { result: OperationResult },
    Accepted { operation_id: OperationId },
    NoChange { result: OperationResult },
    Refused { fault: DomainFault },
}''',
            'pub type DomainCommandReply = CommandReply<DomainDecision>;',
            TAGGED + '''pub enum DomainQueryReply {
    Result { protocol: Protocol, query_id: QueryId, stamp: ReadStamp, result: OperationResult },
    Rejected { protocol: Protocol, query_id: QueryId, fault: DomainFault },
}''',
            TAGGED + '''pub enum OperationCompletion {
    Succeeded { protocol: Protocol, operation_id: OperationId, revision: Revision, result: OperationResult },
    Failed { protocol: Protocol, operation_id: OperationId, revision: Revision, fault: DomainFault },
    OutcomeUnknown { protocol: Protocol, operation_id: OperationId, revision: Revision, correlation_id: CorrelationId },
}''',
            '''impl DomainQueryReply {
    pub fn validate(&self) -> Result<(), String> {
        match self {
            Self::Result { result, .. } => result.check(),
            Self::Rejected { fault, .. } => fault.check(),
        }
    }
}
impl OperationCompletion {
    pub fn validate(&self) -> Result<(), String> {
        match self {
            Self::Succeeded { result, .. } => result.check(),
            Self::Failed { fault, .. } => fault.check(),
            Self::OutcomeUnknown { .. } => Ok(()),
        }
    }
}
/// Recorded-reply consistency: typed result/fault checks, unknown external effects keep a durable
/// operation identity, and `Accepted` names the receipt's own operation.
pub fn validate_command_reply(v: &DomainCommandReply) -> Result<(), String> {
    crate::protocol::shared::validate_domain_reply(v).map_err(str::to_owned)?;
    if let CommandReply::Recorded { receipt, .. } = v {
        match &receipt.decision {
            DomainDecision::Applied { result } | DomainDecision::NoChange { result } => result.check()?,
            DomainDecision::Refused { fault } => {
                fault.check()?;
                if matches!(fault.code, DomainErrorCode::OutcomeUnknown) && receipt.operation_id.is_none() {
                    return Err("unknown effect needs durable operation identity".into());
                }
            }
            DomainDecision::Accepted { operation_id } => {
                if receipt.operation_id.as_ref() != Some(operation_id) {
                    return Err("accepted operation does not match receipt".into());
                }
            }
        }
    }
    Ok(())
}''']
    return '\n'.join(out) + '\n'


def gen_catalog(ops):
    used = set()
    for _, o in ops:
        used |= tokens(o['resultValueType'])
    out = [HEADER, '//! The complete operation catalog: one descriptor per registered operation with its family,',
           '//! owner, envelope, selector, per-mode policy, input decoder, result binding and the schema revisions it negotiates.',
           '#![allow(clippy::large_const_arrays)]',
           *imports(used), 'use super::{AuthorityClass, Decoded, EffectClass, Envelope, ModeBinding, OperationDescriptor, '
           'SchemaRevision, Selector, decode_domain_body, decode_specialized, schema_of};',
           'use crate::admission::AdmissionError;', 'use crate::operations::{self as ops, OperationInput};',
           'use crate::registry::Mode;', 'use serde_json::Value;', '',
           f'pub(super) const FAMILIES: [&str; {len(REGISTER["families"])}] = [',
           *[f'    "{f["family"]}",' for f in REGISTER['families']], '];', '',
           f'pub(super) static CATALOG: [OperationDescriptor; {len(ops)}] = [']
    fns = []
    index = []
    for i, (fam, o) in enumerate(ops):
        n = o['operation']
        family = fam['family']
        policies = {m['mode']: m for m in o['modePolicies']}
        modes = []
        for mode, ty, variant, fs in bindings(o):
            fn = f'decode_{snake(n)}_{mode.lower()}'
            wrap = f'|i| OperationInput::{pascal(family)}(ops::{family}::Input::{variant}(i))'
            if fs is None:
                ty_path = ty
                fns.append(f'fn {fn}(v: Value, revision: SchemaRevision) -> Result<Decoded, AdmissionError> {{\n'
                           f'    decode_specialized::<{ty}>(v, revision, {wrap})\n}}')
            else:
                ty_path = f'ops::{family}::{ty}'
                fns.append(f'fn {fn}(v: Value, revision: SchemaRevision) -> Result<Decoded, AdmissionError> {{\n'
                           f'    decode_domain_body::<{ty_path}>("{n}", Mode::{mode}, revision, v, {wrap})\n}}')
            p = policies[mode]
            if p['authority'] not in AUTHORITY or p['effect'] not in EFFECT:
                fail('unmapped mode policy for ' + n)
            modes.append(f'ModeBinding {{ mode: Mode::{mode}, authority: AuthorityClass::{AUTHORITY[p["authority"]]}, '
                         f'effect: EffectClass::{EFFECT[p["effect"]]}, input_type: "{ty_path.replace("crate::protocol::", "").replace("ops::", "")}", '
                         f'decode: {fn}, input_schema: schema_of::<{ty_path}> }}')
        sel = o['selectionConstraint']
        selector = f'Some(Selector {{ pointer: "{sel["pointer"]}", equals: "{sel["equals"]}" }})' if sel else 'None'
        envelope = ('Envelope::Domain' if o['inputSchema'] == 'domain-request.schema.json'
                    else f'Envelope::Specialized {{ schema: "{o["inputSchema"].removesuffix(".schema.json")}" }}')
        out.append(f'    OperationDescriptor {{ name: "{n}", family: "{family}", owner: "{fam["owner"]}", '
                   f'envelope: {envelope}, selector: {selector}, modes: &[{", ".join(modes)}], '
                   f'result_type: "{o["resultValueType"]}", result_schema: schema_of::<{rust(o["resultValueType"])}>, '
                   f'completion: {"true" if o.get("completionSchema") else "false"}, '
                   f'revisions: &[{", ".join(f"SchemaRevision({r})" for r in REVISIONS.get(n, [1]))}] }},')
        index.append(f'        "{n}" => Some({i}),')
    out += ['];', '', 'pub(super) fn index_of(name: &str) -> Option<usize> {', '    match name {', *index,
            '        _ => None,', '    }', '}', '', *fns]
    return '\n'.join(out) + '\n'


